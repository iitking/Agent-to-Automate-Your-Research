class NumberedCanvas(canvas.Canvas):
    """Adds 'Page X of Y' and header to every page."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 9)
        self.setFillColor(colors.HexColor("#64748b"))

        # Running header (pages > 1)
        if self._pageNumber > 1:
            self.drawString(54, 750, "Autonomous AI Research Report")
            self.setStrokeColor(colors.HexColor("#e2e8f0"))
            self.setLineWidth(0.5)
            self.line(54, 742, 558, 742)

        # Running footer
        page_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(558, 36, page_text)
        self.drawString(54, 36, "Confidential & Evidence-Backed Research · Generated by ResearchAgent")
        self.setStrokeColor(colors.HexColor("#e2e8f0"))
        self.setLineWidth(0.5)
        self.line(54, 48, 558, 48)

        self.restoreState()


def generate_pdf_export(research_id: str, title: str, markdown_content: str) -> str:
    """
    Generates a professional PDF report using ReportLab.
    Validates file creation and returns the generated absolute path.
    """
    os.makedirs(settings.EXPORTS_DIR, exist_ok=True)
    pdf_path = os.path.join(settings.EXPORTS_DIR, f"{research_id}.pdf")

    doc = SimpleDocTemplate(
        pdf_path,
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=54,
        bottomMargin=54,
    )

    styles = getSampleStyleSheet()

    # Custom styles
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=24,
        leading=28,
        textColor=colors.HexColor("#0f172a"),
        spaceAfter=12,
    )

    h1_style = ParagraphStyle(
        "DocH1",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=15,
        leading=19,
        textColor=colors.HexColor("#1e293b"),
        spaceBefore=16,
        spaceAfter=8,
        keepWithNext=True,
    )

    h2_style = ParagraphStyle(
        "DocH2",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=12,
        leading=16,
        textColor=colors.HexColor("#334155"),
        spaceBefore=12,
        spaceAfter=6,
        keepWithNext=True,
    )

    body_style = ParagraphStyle(
        "DocBody",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#334155"),
        spaceAfter=8,
    )

    bullet_style = ParagraphStyle(
        "DocBullet",
        parent=body_style,
        leftIndent=15,
        firstLineIndent=-10,
        spaceAfter=4,
    )

    callout_style = ParagraphStyle(
        "DocCallout",
        parent=body_style,
        fontName="Helvetica-Oblique",
        fontSize=9.5,
        leading=13.5,
        textColor=colors.HexColor("#1e293b"),
        backColor=colors.HexColor("#f1f5f9"),
        borderPadding=8,
        spaceBefore=8,
        spaceAfter=8,
    )

    story = []

    # Title & Header
    clean_title = title.replace("\n", " ").strip()
    story.append(Paragraph(clean_title, title_style))
    story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#2563eb"), spaceAfter=14))

    # Parse markdown lines
    lines = markdown_content.split("\n")
    in_code_block = False

    for line in lines:
        stripped = line.strip()

        if stripped.startswith("```"):
            in_code_block = not in_code_block
            continue

        if in_code_block:
            continue

        if not stripped:
            continue

        # Skip main # Title if it mirrors document title
        if stripped.startswith("# ") and stripped[2:].strip().lower() == clean_title.lower():
            continue

        # Headings
        if stripped.startswith("### "):
            story.append(Paragraph(stripped[4:], h2_style))
        elif stripped.startswith("## "):
            story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#cbd5e1"), spaceBefore=10, spaceAfter=6))
            story.append(Paragraph(stripped[3:], h1_style))
        elif stripped.startswith("# "):
            story.append(Paragraph(stripped[2:], h1_style))
        elif stripped.startswith("> "):
            # Callout
            quote_text = stripped[2:].strip()
            story.append(Paragraph(quote_text, callout_style))
        elif stripped.startswith("- ") or stripped.startswith("* "):
            bullet_text = stripped[2:].strip()
            # Convert markdown bold/italics
            bullet_html = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", bullet_text)
            bullet_html = re.sub(r"\*([^*]+)\*", r"<i>\1</i>", bullet_html)
            story.append(Paragraph(f"• {bullet_html}", bullet_style))
        elif re.match(r"^\d+\.\s+", stripped):
            num_match = re.match(r"^(\d+\.)\s+(.+)$", stripped)
            if num_match:
                prefix, content = num_match.groups()
                item_html = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", content)
                item_html = re.sub(r"\*([^*]+)\*", r"<i>\1</i>", item_html)
                story.append(Paragraph(f"<b>{prefix}</b> {item_html}", bullet_style))
        else:
            # Body text
            text_html = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", stripped)
            text_html = re.sub(r"\*([^*]+)\*", r"<i>\1</i>", text_html)
            # Markdown links
            text_html = re.sub(r'\[([^\]]+)\]\(([^\)]+)\)', r'<u><font color="#2563eb">\1</font></u>', text_html)
            story.append(Paragraph(text_html, body_style))

    doc.build(story, canvasmaker=NumberedCanvas)

    if not os.path.exists(pdf_path) or os.path.getsize(pdf_path) == 0:
        raise RuntimeError("PDF generation failed or output file is empty.")

    logger.info(f"PDF report generated successfully at {pdf_path}")
    return pdf_path
